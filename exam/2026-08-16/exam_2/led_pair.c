/*
 * ตั้งขา LED ทั้ง 4 ดวงเป็น output ทั้งหมด (เขียนตรง ๆ ทีละขา)
 */
void led_pair_init(void)
{
    /* PA5 = D13 = น้ำเงิน (คู่นอก) */
    GPIOA->MODER &= ~(0x3u << (5u * 2u));
    GPIOA->MODER |= (0x1u << (5u * 2u));

    /* PA6 = D12 = แดง (คู่กลาง) */
    GPIOA->MODER &= ~(0x3u << (6u * 2u));
    GPIOA->MODER |= (0x1u << (6u * 2u));

    /* PA7 = D11 = เหลือง (คู่กลาง) */
    GPIOA->MODER &= ~(0x3u << (7u * 2u));
    GPIOA->MODER |= (0x1u << (7u * 2u));

    /* PB6 = D10 = เขียว (คู่นอก) */
    GPIOB->MODER &= ~(0x3u << (6u * 2u));
    GPIOB->MODER |= (0x1u << (6u * 2u));
}

/*
 * แปลงค่า ADC (0-4095) เป็นระดับ 0-2 แล้วเปิด/ปิดแต่ละคู่ตามระดับนั้น
 * เหตุผล: หาร 4096 ออกเป็น 3 ช่วงเท่า ๆ กัน
 * ระดับ 0 = ดับหมด, ระดับ 1 = คู่กลางติด, ระดับ 2 = ติดครบทั้ง 2 คู่
 */
void led_pair_update(uint16_t adc_value)
{
    uint8_t level;

    level = (uint8_t)((adc_value * 3u) / 4096u);

    /* คู่กลาง (แดง=PA6, เหลือง=PA7) ติดตั้งแต่ระดับ 1 ขึ้นไป */
    if (level >= 1u)
    {
        GPIOA->ODR |= (1u << 6u);
        GPIOA->ODR |= (1u << 7u);
    }
    else
    {
        GPIOA->ODR &= ~(1u << 6u);
        GPIOA->ODR &= ~(1u << 7u);
    }

    /* คู่นอก (น้ำเงิน=PA5, เขียว=PB6) ติดเฉพาะระดับ 2 (หมุนทวนเข็มสุด) */
    if (level >= 2u)
    {
        GPIOA->ODR |= (1u << 5u);
        GPIOB->ODR |= (1u << 6u);
    }
    else
    {
        GPIOA->ODR &= ~(1u << 5u);
        GPIOB->ODR &= ~(1u << 6u);
    }
}

