/* Includes ------------------------------------------------------------------*/
#define STM32F411xE         /* บอก CMSIS ว่าใช้ชิปรุ่น STM32F411xE (Nucleo-F411RE) */
#include "stm32f4xx.h"
#include "adc.h"
#include "led_pair.h"

/* Private includes ------------------------------------------------------------*/

/* Private typedef ------------------------------------------------------------*/

/* Private define ------------------------------------------------------------*/

/* Private macro ------------------------------------------------------------*/

/* Private constants ------------------------------------------------------------*/

/* Private variables ------------------------------------------------------------*/

/* External variables ------------------------------------------------------------*/

/* Private function prototypes ------------------------------------------------*/
static void clock_init(void);

/* Private user code ------------------------------------------------------------*/

/* main() ------------------------------------------------------------*/
int main(void)
{
    uint16_t pot_value;

    clock_init();
    adc_init();
    led_pair_init();

    while (1)
    {
        /* อ่านค่า potentiometer ซ้ำ ๆ ตลอดเวลา แล้วอัปเดตว่าคู่ไหนติดบ้าง
         * ให้ตรงกับตำแหน่งปัจจุบันทันที (ไม่ต้อง interrupt เพราะโจทย์ข้อนี้
         * ไม่ได้บังคับ) */
        pot_value = adc_read();
        led_pair_update(pot_value);
    }

    return 0;
}

/* Callback functions ------------------------------------------------------------*/

/* Private functions ------------------------------------------------------------*/

/*
 * เปิด clock ให้ครบทุก peripheral ที่ใช้: GPIOA (LED 3 ดวง + potentiometer),
 * GPIOB (LED ดวงที่ 4), ADC1 (อ่านค่า potentiometer)
 */
static void clock_init(void)
{
    RCC->AHB1ENR |= (RCC_AHB1ENR_GPIOAEN | RCC_AHB1ENR_GPIOBEN);
    RCC->APB2ENR |= RCC_APB2ENR_ADC1EN;
}
