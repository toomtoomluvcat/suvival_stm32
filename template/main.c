/*********************************************************************
 * @fn                 - clock_init
 * @brief              - เปิด clock ให้ GPIOA, GPIOB, GPIOC และ SYSCFG
 *
 * @return             - void
 *
 * @Note               -
 *//////////////////////////////////////////////////////////////////////
static void clock_init(void)
{
    RCC->AHB1ENR |= (RCC_AHB1ENR_GPIOAEN | RCC_AHB1ENR_GPIOBEN | RCC_AHB1ENR_GPIOCEN);
    RCC->APB2ENR |= RCC_APB2ENR_SYSCFGEN;
}
