/*********************************************************************
 * @fn                 - seven_seg_init
 * @brief              - ตั้งค่าขา PC7, PA8, PB10, PA9 เป็น output สำหรับควบคุม 7-segment
 *
 * @return             - void
 *
 * @Note               - ต้องเปิด clock ของ GPIOA/GPIOB/GPIOC ก่อนเรียกฟังก์ชันนี้
 *//////////////////////////////////////////////////////////////////////
void seven_seg_init(void)
{
    GPIOC->MODER &= ~(0x3u << (7u * 2u));
    GPIOC->MODER |=  (0x1u << (7u * 2u));    /* PC7 = bit 2^0 */

    GPIOA->MODER &= ~(0x3u << (8u * 2u));
    GPIOA->MODER |=  (0x1u << (8u * 2u));    /* PA8 = bit 2^1 */

    GPIOB->MODER &= ~(0x3u << (10u * 2u));
    GPIOB->MODER |=  (0x1u << (10u * 2u));   /* PB10 = bit 2^2 */

    GPIOA->MODER &= ~(0x3u << (9u * 2u));
    GPIOA->MODER |=  (0x1u << (9u * 2u));    /* PA9 = bit 2^3 */
}

/*********************************************************************
 * @fn                 - seven_seg_display
 * @brief              - แสดงเลข 0-9 บน 7-segment โดยแยกบิตแล้วตั้งค่าแต่ละขา
 *
 * @param[in]          - number : เลขที่ต้องการแสดง (0-9)
 *
 * @return             - void
 *
 * @Note               -
 *//////////////////////////////////////////////////////////////////////
void seven_seg_display(uint8_t number)
{
    uint8_t bit0 = (uint8_t)((number >> 0u) & 1u);
    uint8_t bit1 = (uint8_t)((number >> 1u) & 1u);
    uint8_t bit2 = (uint8_t)((number >> 2u) & 1u);
    uint8_t bit3 = (uint8_t)((number >> 3u) & 1u);

    if (bit0 == 1u)
    {
        GPIOC->ODR |= (1u << 7u);
    }
    else
    {
        GPIOC->ODR &= ~(1u << 7u);
    }

    if (bit1 == 1u)
    {
        GPIOA->ODR |= (1u << 8u);
    }
    else
    {
        GPIOA->ODR &= ~(1u << 8u);
    }

    if (bit2 == 1u)
    {
        GPIOB->ODR |= (1u << 10u);
    }
    else
    {
        GPIOB->ODR &= ~(1u << 10u);
    }

    if (bit3 == 1u)
    {
        GPIOA->ODR |= (1u << 9u);
    }
    else
    {
        GPIOA->ODR &= ~(1u << 9u);
    }
}

