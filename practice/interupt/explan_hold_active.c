#include <stdint.h>
#include "stm32f4xx.h"

/* ===== Prototypes: ต้องประกาศก่อน main() เสมอ
   เหตุผล: compiler อ่านจากบนลงล่าง ถ้าไม่มี prototype
   compiler จะไม่รู้จักฟังก์ชันตอนเจอการเรียกใช้ใน main() ===== */
static void clock_init(void);
static void button_exti_init(void);

/* ===== ตัวแปร global เก็บค่าตัวนับ
   เหตุผลที่ต้องเป็น "volatile": เพราะตัวแปรนี้ถูกแก้ใน ISR (interrupt)
   ซึ่งเกิดขึ้นได้ทุกเมื่อ ไม่ใช่แค่ตอน CPU รัน main loop ปกติ
   ถ้าไม่ใส่ volatile compiler อาจ optimize โดยคิดว่าค่าตัวนี้ไม่เปลี่ยน
   แล้วอ่านค่าเก่าที่เก็บไว้ใน register แทนของจริงใน memory ===== */
static volatile uint8_t counter = 0u;

int main(void)
{
    /* เรียก init function ทั้งหมดก่อนเข้า loop เสมอ
       เพื่อให้ hardware พร้อมทำงานก่อนเริ่ม logic จริง */
    clock_init();
    button_exti_init();

    /* while(1) ว่างเปล่า เพราะทุกอย่างทำงานผ่าน interrupt
       (ISR) ทั้งหมด ไม่ต้องมี logic ใน main loop เลย
       ⚠️ ห้ามลบ while(1) นี้ทิ้ง เพราะ embedded program
       ต้องไม่ return ออกจาก main เด็ดขาด (ไม่มี OS
       ให้กลับไปหา จะทำให้ CPU รันโค้ดขยะต่อ) */
    while (1)
    {
        /* No action: logic ทั้งหมดอยู่ใน ISR */
    }

    return 0;   /* บรรทัดนี้ไม่มีวันถูกรันจริง แต่ใส่ไว้เพราะ
                   ฟังก์ชัน int ต้องมี return ตาม C standard */
}

static void clock_init(void)
{
    /* เปิด clock ให้ GPIOB ก่อน เพราะปุ่มเราต่อที่ PB3
       เหตุผลที่ต้องเปิด: STM32 ปิด clock ของ peripheral
       ทุกตัวไว้ตอน reset (เพื่อประหยัดพลังงาน) ถ้าไม่เปิด
       clock ก่อน การเขียน register ของ GPIOB จะไม่มีผลใดๆ
       เลย (เหมือนเขียนไปแต่ peripheral ไม่ได้ทำงานรับค่า) */
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOBEN;

    /* เปิด clock ให้ SYSCFG เพราะการใช้ EXTI ต้องพึ่งพา
       SYSCFG->EXTICR ในการเลือกว่า EXTI line แต่ละเส้น
       จะรับสัญญาณจาก Port ไหน (A/B/C) ถ้าไม่เปิด clock
       ตัวนี้ การตั้งค่า EXTICR ในขั้นตอนถัดไปจะไม่มีผล */
    RCC->APB2ENR |= RCC_APB2ENR_SYSCFGEN;
}

static void button_exti_init(void)
{
    /* ----- ขั้นที่ 1: ตั้งขา PB3 ให้เป็น GPIO Input -----
       เขียน 00 ลงใน MODER bit-field ของขา 3
       (จริงๆ ค่า default หลัง reset ก็เป็น input (00) อยู่
       แล้ว แต่เขียนซ้ำไว้กันเหนียว เผื่อมีโค้ดอื่นเปลี่ยนไปก่อน) */
    GPIOB->MODER &= ~(0x3u << (3u * 2u));

    /* ----- ขั้นที่ 2: เปิดใช้ Pull-up resistor ภายในตัวชิป -----
       เหตุผล: ปุ่มเราต่อแบบวงจรกดแล้วครบวงจรลงกราวด์ (active-low)
       ถ้าไม่กด ขาจะ "ลอย" (floating) ไม่มีค่าที่แน่นอน อ่านได้ทั้ง
       0 หรือ 1 แบบสุ่ม เลยต้องใช้ pull-up ดึงขาขึ้นไปที่ลอจิก 1
       ไว้ก่อนเป็นค่าเริ่มต้น พอกดปุ่มค่อยลงไปเป็น 0 */
    GPIOB->PUPDR &= ~(0x3u << (3u * 2u));   /* เคลียร์ค่าเดิมก่อน (จำเป็นเสมอก่อนตั้งค่าใหม่) */
    GPIOB->PUPDR |=  (0x1u << (3u * 2u));   /* 01 = Pull-up ตาม datasheet */

    /* ----- ขั้นที่ 3: ผูก EXTI line 3 เข้ากับ Port B -----
       เหตุผลที่ต้องมีขั้นตอนนี้: EXTI line แต่ละเส้น (0-15)
       ใช้ร่วมกันได้ทั้ง 3 พอร์ต (เช่น PA3, PB3, PC3 ทุกตัวใช้
       line 3 เหมือนกัน) เพราะฉะนั้นต้องบอกชิปให้ชัดว่า
       "line 3 ของฉัน หมายถึงขาบน Port ไหน"

       สูตรหา index/shift: index = line÷4 = 3÷4 = 0
                            shift = (line mod 4)×4 = (3 mod 4)×4 = 12 */
    SYSCFG->EXTICR[0] &= ~(0xFu << 12u);    /* เคลียร์ 4 บิตเดิมก่อน */
    SYSCFG->EXTICR[0] |=  (0x1u << 12u);    /* 0x1 = รหัส Port B (A=0x0, B=0x1, C=0x2) */

    /* ----- ขั้นที่ 4: ตั้งชนิด edge ที่จะ trigger interrupt -----
       เลือก falling edge (สัญญาณตกจาก 1 ลง 0) เพราะเป็นจังหวะ
       ที่ปุ่มถูกกดลงพอดี (pull-up ทำให้ค่าเริ่มที่ 1 พอกดจะลง 0)

       ข้อดีสำคัญ: การใช้ edge-trigger (ไม่ใช่ level-trigger)
       ทำให้ต่อให้กดปุ่มค้างไว้นานแค่ไหน สัญญาณก็จะนิ่งอยู่ที่ 0
       ไม่มีขอบใหม่เกิดซ้ำ interrupt จึงยิงแค่ครั้งเดียวต่อการกด
       1 ครั้งโดยอัตโนมัติ ไม่ต้องเขียน debounce logic เอง */
    EXTI->FTSR |= (1u << 3u);

    /* ----- ขั้นที่ 5: Unmask ให้ line 3 ส่ง interrupt ออกมาได้จริง -----
       ถ้าไม่ unmask ตรงนี้ ต่อให้ FTSR ตั้งไว้ถูกและมีการกด
       ปุ่มจริง สัญญาณ interrupt ก็จะถูก "บล็อก" ไม่ส่งไปหา NVIC */
    EXTI->IMR |= (1u << 3u);

    /* ----- ขั้นที่ 6: เปิดให้ CPU (ผ่าน NVIC) ยอมรับ interrupt
       จาก EXTI line 3 -----
       นี่คือ "สวิตช์ใหญ่" อีกชั้นนึง ถ้าไม่เปิดตรงนี้ ต่อให้
       EXTI ส่งสัญญาณมาแล้ว CPU ก็จะเพิกเฉยไม่กระโดดไปทำ ISR */
    NVIC_EnableIRQ(EXTI3_IRQn);
}

/* ===== ISR: ฟังก์ชันนี้ CPU จะกระโดดมาทำงานเองอัตโนมัติทันที
   ที่มีสัญญาณ interrupt เกิดขึ้นจาก EXTI line 3 (ไม่ได้ถูกเรียก
   จากที่ไหนในโค้ดเราเลย แต่ชื่อฟังก์ชันต้องตรงกับที่กำหนดไว้ใน
   vector table ของ CMSIS เป๊ะๆ ถึงจะทำงาน) ===== */
void EXTI3_IRQHandler(void)
{
    /* เช็คก่อนว่า pending bit ของ line 3 ติดจริงไหม
       เหตุผลที่ต้องเช็ค: ในบางกรณี (โดยเฉพาะ line ที่ใช้ร่วมกัน
       หลายขาอย่าง EXTI9_5 หรือ EXTI15_10) handler เดียวอาจถูก
       เรียกจากหลาย line พร้อมกัน ต้องเช็คให้ชัวร์ว่าเป็น line
       ที่เราสนใจจริงก่อนทำงาน (ใน line เดี่ยวแบบนี้ไม่จำเป็น
       เท่าไหร่ แต่ใส่ไว้เป็นนิสัยที่ดีและกัน false trigger) */
    if ((EXTI->PR & (1u << 3u)) != 0u)
    {
        /* เคลียร์ pending bit โดยการ "เขียน 1 ทับ" (ไม่ใช่เขียน 0!)
           นี่คือกฎพิเศษของ register นี้ตาม datasheet — ถ้าไม่เคลียร์
           ตรงนี้ CPU จะคิดว่ายังมี interrupt ค้างอยู่ตลอด แล้วจะ
           วนกลับมาเรียก ISR นี้ซ้ำไม่หยุด (ค้างทั้งโปรแกรม) */
        EXTI->PR |= (1u << 3u);

        /* งานจริงที่ต้องการให้เกิดขึ้นเมื่อกดปุ่ม 1 ครั้ง
           ทำเพียงบรรทัดเดียวเพราะสัญญาณ falling edge รับประกัน
           แล้วว่า ISR นี้จะถูกเรียกแค่ 1 ครั้งต่อการกด 1 ครั้ง */
        counter++;
    }
    else
    {
        /* No action: ไม่ใช่ line 3 ที่ trigger (เผื่อกรณีอนาคต
           ถ้าเปลี่ยนไปใช้ handler แบบใช้ร่วมกันหลาย line) */
    }
}